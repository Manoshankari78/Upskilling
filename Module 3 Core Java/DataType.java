public class DataType {
    public static void main(String[] args){
        int a=10;
        double b=10.5;
        float c=10.5f;
        char d='A';
        boolean e=true;
        System.out.println("Integer: "+a);
        System.out.println("Double: "+b);
        System.out.println("Float: "+c);
        System.out.println("Character: "+d);
        System.out.println("Boolean: "+e);
    }
}
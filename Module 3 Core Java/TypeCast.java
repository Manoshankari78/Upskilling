public class TypeCast{
    public static void main(String[] args){
        int a=35;
        double b=a;
        System.out.println("Integer: "+a);
        System.out.println("Double: "+b);
        double c=10.5;
        int d=(int)c;
        System.out.println("Double: "+c);
        System.out.println("Integer: "+d);
    }
}